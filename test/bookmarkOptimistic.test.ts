import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import { QueryClient } from '@tanstack/react-query';
import { toggleBookmark } from '../src/util/LocalLibrary/logic';
import { mergeBookmarkFlags } from '../src/util/LocalLibrary/remoteBookmarks';

test('remote bookmarks appear before server success and roll back on failure without refetching folders', async () => {
  const client = new QueryClient();
  const film = { id: '1', link: 'https://rezka.ag/films/1-film.html', title: 'Film', poster: '', subtitle: '2020', type: 'FILM', bookmarks: [{ id: 'folder', title: 'Later (0)', isBookmarked: false }] };
  const library = { categories: [{ id: 'folder', title: 'Later', filmIds: [], createdAt: 1 }], films: {} };
  const initial = { films: [], currentPage: 1, totalPages: 1 };
  client.setQueryData(['film', film.link], film);
  client.setQueryData(['films', 'bookmarks', 'folder', null], initial);
  client.setQueryData(['bookmarks'], [{ id: 'folder', title: 'Later (0)' }]);
  let options: any, serverCalls = 0;
  const require = createRequire(import.meta.url);
  const exports = {};
  const source = readFileSync('src/component/BookmarksOverlay/BookmarksOverlay.container.tsx', 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
  runInNewContext(compiled, { exports, require: (name: string) => {
    if (name === '@tanstack/react-query') return { useQueryClient: () => client, useMutation: (value: unknown) => { options = value; return { mutate() {}, isPending: false }; } };
    if (name === 'react') return { useState: (value: unknown) => [value, () => {}] };
    if (name === 'react/jsx-runtime') return require(name);
    if (name === 'react-native') return { Platform: { OS: 'web' } };
    if (name === 'Context/ConfigContext') return { useConfigContext: () => ({ isTV: false, isLocalLibrary: false }) };
    if (name === 'Context/ServiceContext') return { useServiceContext: () => ({ currentService: { addBookmark: () => { serverCalls++; return new Promise(() => {}); } } }) };
    if (name === 'Hooks/useLocalLibrary') return { useLocalBookmarks: () => library };
    if (name === 'Hooks/useBookmarkLibrary') return { useBookmarkLibrary: () => library };
    if (name === 'Util/LocalLibrary/identity') return { matchingBookmarkIds: () => [], bookmarkFilmIdentity: () => ({ sources: [] }) };
    if (name === 'Util/LocalLibrary/logic') return { toggleBookmark };
    if (name === 'Util/LocalLibrary/remoteBookmarks') return { mergeBookmarkFlags };
    if (name === 'Util/LocalLibrary') return { getLocalBookmarksForFilm: () => [] };
    if (name === 'Util/Film') return { filmToFilmCard: (value: unknown) => value };
    if (name === 'Util/Query') return { queryKeys: { bookmarks: () => ['bookmarks'], films: { bookmarks: () => ['films', 'bookmarks'] } } };
    if (name.includes('ContentSource')) return { ContentSource: { REZKA: 'REZKA' } };
    return {};
  } });
  (exports as any).BookmarksOverlayContainer({ film });
  const variables = { bookmarkId: 'folder', isChecked: true };
  const context = await options.onMutate(variables);
  assert.equal(serverCalls, 0);
  assert.equal((client.getQueryData(['films', 'bookmarks', 'folder', null]) as any).films[0].id, '1');
  assert.equal((client.getQueryData(['film', film.link]) as any).bookmarks[0].isBookmarked, true);
  options.onError(new Error('504'), variables, context);
  assert.equal(client.getQueryData(['films', 'bookmarks', 'folder', null]), initial);
  assert.equal((client.getQueryData(['film', film.link]) as any).bookmarks[0].isBookmarked, false);
  options.onSettled();
  assert.equal(client.getQueryState(['films', 'bookmarks', 'folder', null])?.fetchStatus, 'idle');
  client.clear();
});